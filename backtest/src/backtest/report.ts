// results/summary.md, generated from the same object as summary.json.

import type { Summary } from "./analysis.ts";

const pct = (x: number | null, d = 1): string => (x === null ? "n/a" : `${(x * 100).toFixed(d)}%`);
const money = (x: number): string =>
  `${x < 0 ? "-" : ""}$${Math.abs(x).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const signedPct = (x: number): string => `${x >= 0 ? "+" : ""}${(x * 100).toFixed(1)}%`;

function table(header: string[], rows: Array<Array<string | number>>): string {
  return [
    `| ${header.join(" | ")} |`,
    `|${header.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

type Hedge = Summary["hedge_neutral"];

function hedgeTable(h: Hedge): string {
  const b = h.buyer;
  const s = h.seller;
  return table(
    ["", "Buyer unhedged", "Buyer hedged", "Seller unhedged", "Seller hedged"],
    [
      ["Mean per week", money(b.unhedged_weekly_cost.mean), money(b.hedged_weekly_cost.mean), money(s.unhedged_weekly_revenue.mean), money(s.hedged_weekly_revenue.mean)],
      ["Std dev per week", money(b.unhedged_weekly_cost.sd), money(b.hedged_weekly_cost.sd), money(s.unhedged_weekly_revenue.sd), money(s.hedged_weekly_revenue.sd)],
      ["Std dev of the surprise (vs. cost at the anchor)", money(b.sd_of_surprise.unhedged), money(b.sd_of_surprise.hedged), money(s.sd_of_surprise.unhedged), money(s.sd_of_surprise.hedged)],
      [
        "Largest week-on-week move against you",
        b.largest_week_on_week_increase.unhedged ? `+${money(b.largest_week_on_week_increase.unhedged.change)} (${b.largest_week_on_week_increase.unhedged.to_week})` : "n/a",
        b.largest_week_on_week_increase.hedged ? `+${money(b.largest_week_on_week_increase.hedged.change)} (${b.largest_week_on_week_increase.hedged.to_week})` : "n/a",
        s.largest_week_on_week_decrease.unhedged ? `${money(s.largest_week_on_week_decrease.unhedged.change)} (${s.largest_week_on_week_decrease.unhedged.to_week})` : "n/a",
        s.largest_week_on_week_decrease.hedged ? `${money(s.largest_week_on_week_decrease.hedged.change)} (${s.largest_week_on_week_decrease.hedged.to_week})` : "n/a",
      ],
      ["Total over the sample", money(b.unhedged_weekly_cost.total), money(b.hedged_weekly_cost.total), money(s.unhedged_weekly_revenue.total), money(s.hedged_weekly_revenue.total)],
      ["Dollars locked per week (mean)", "", money(b.locked_per_week.mean), "", money(s.locked_per_week.mean)],
    ],
  );
}

export interface OrnnGap {
  overlap: number;
  first: string | null;
  mean_signed_pct_gap: number | null;
}

export function renderMarkdown(s: Summary, ornn?: OrnnGap): string {
  const ornnText =
    ornn && ornn.overlap && ornn.mean_signed_pct_gap !== null
      ? ` Where it overlaps (${ornn.overlap} days from ${ornn.first}) the composite sits on average ${Math.abs(ornn.mean_signed_pct_gap).toFixed(0)}% ${ornn.mean_signed_pct_gap > 0 ? "above" : "below"} Ornn's transaction-based H100 index (\`data/derived/validation.json\`): this is a list-price index, and a fixing on transaction prices would sit elsewhere and might move differently.`
      : "";
  const P = s.parameters;
  const rec = s.recommendation;
  const out: string[] = [];
  out.push("# Weir backtest: H100 week-ahead band, " + `${s.weeks.first} to ${s.weeks.last}`);
  out.push("");
  out.push("Generated by `pnpm --filter @weir/backtest run backtest` from `data/derived/` only. Every number here is also in `summary.json`.");
  out.push("");
  out.push("## Sample");
  out.push("");
  out.push(
    table(
      ["Item", "Value"],
      [
        ["Index window", `${s.data.first_day} to ${s.data.last_day} (${s.data.days} days)`],
        ["Days with an index value", `${s.data.days_with_index} (${s.data.days_without_index} without)`],
        ["First and last day with an index value", `${s.data.first_index_day} to ${s.data.last_index_day}`],
        ["Candidate delivery weeks (inside that span)", s.weeks.candidate_mondays],
        ["Weeks kept", s.weeks.kept],
        ["Weeks dropped: anchor older than 3 days", s.weeks.excluded.filter((e) => e.reason === "stale_anchor").length],
        ["Weeks dropped: fewer than 4 daily prints", s.weeks.excluded.filter((e) => e.reason === "few_prints").length],
        ["Usage assumed", `${P.hoursPerWeek} GPU-hours a week (8 GPUs, 168 h)`],
      ],
    ),
  );
  out.push("");
  out.push("## 1. Band coverage");
  out.push("");
  out.push("`move = fixing / anchor - 1`, where the anchor is the last daily print before the auction opens (8 to 10 days before delivery starts) and the fixing is the mean of the delivery week's daily prints.");
  out.push("");
  const m = s.move;
  out.push(
    table(
      ["Statistic", ...Object.keys(m.percentiles), "min", "max", "mean", "sd"],
      [["move", ...Object.values(m.percentiles).map((v) => signedPct(v)), signedPct(m.min), signedPct(m.max), signedPct(m.mean), pct(m.sd)]],
    ),
  );
  out.push("");
  out.push(`Largest rises: ${m.largest_rises.map((x) => `${x.week} ${signedPct(x.move)}`).join(", ")}.`);
  out.push(`Largest falls: ${m.largest_falls.map((x) => `${x.week} ${signedPct(x.move)}`).join(", ")}.`);
  out.push("");
  out.push(
    table(
      ["band_bps", "Half-width", "Weeks", "Inside", "Above cap", "Below floor", "Share inside", "95% interval (Wilson)"],
      s.coverage.map((c) => [
        c.band_bps,
        `±${c.band_bps / 100}%`,
        c.weeks,
        c.inside,
        c.above_cap,
        c.below_floor,
        pct(c.share_inside),
        `${pct(c.share_inside_wilson95[0])} to ${pct(c.share_inside_wilson95[1])}`,
      ]),
    ),
  );
  out.push("");
  out.push(`**Recommendation: \`band_bps = ${rec.band_bps}\`** (${rec.met ? "rule met" : "rule NOT met by any value in the grid; largest value shown"}). Rule: ${rec.rule}.`);
  out.push("");
  out.push(
    `For context: the smallest band with no breach at all in this sample is ${rec.no_breach_band_bps ?? "none in the grid"}; the smallest whose 95% lower confidence bound on coverage reaches ${P.coverageTarget * 100}% is ${rec.lower_bound_band_bps ?? "none in the grid (the sample is too short to show 95% coverage with confidence at any width tested)"}.`,
  );
  out.push("");
  out.push(
    `What ${s.weeks.kept} weeks cannot tell you: a share measured on this many weeks has the wide interval shown above, so "95%" here is consistent with a true rate several points lower. Weeks are not independent (prices trend for months), which makes the real uncertainty larger than the Wilson interval. A one-in-a-hundred-weeks move has a ${pct(0.99 ** s.weeks.kept, 0)} chance of not appearing at all in ${s.weeks.kept} weeks, so the worst move here is not the worst move possible.`,
  );
  out.push("");
  const FP = s.robustness_fixed_panel;
  if ("coverage" in FP && FP.coverage) {
    out.push("### Robustness: a fixed provider panel");
    out.push("");
    out.push(
      `The composite's provider set changed on ${FP.composition_changes} of its days (snapshots and archive captures come and go), and the median can step when it does. Rebuilt from a fixed panel (${FP.providers.join(", ")}: ${FP.rule}), ${FP.weeks} weeks qualify, the move sd is ${pct(FP.move!.sd)} (composite: ${pct(m.sd)}), and coverage is:`,
    );
    out.push("");
    out.push(table(["band_bps", ...FP.coverage.map((c) => String(c.band_bps))], [["Share inside", ...FP.coverage.map((c) => `${pct(c.share_inside)} (${c.inside}/${c.weeks})`)]]));
    out.push("");
  }
  out.push(`## 2. Hedge at a neutral price (band_bps = ${rec.band_bps}, auction clears at the anchor)`);
  out.push("");
  out.push(hedgeTable(s.hedge_neutral));
  out.push("");
  out.push(
    `Share of weekly cost variance removed: ${pct(s.hedge_neutral.buyer.variance_removed)} of the raw weekly cost, ${pct(s.hedge_neutral.buyer.surprise_variance_removed)} of the surprise. The raw figure is small because the hedge fixes next week's price at this week's level, so the hedged cost still follows the market with a lag; what it removes is the part of a week's bill you could not know when you bought. Buyer and seller columns match because, at the same LONG price, the buyer's hedged cost per GPU-hour and the seller's hedged revenue are the same expression, \`fixing - LONG payout + p\`.`,
  );
  out.push("");
  out.push(`### Weeks the band capped the hedge (${s.capped_weeks.length})`);
  out.push("");
  out.push(
    s.capped_weeks.length
      ? table(
          ["Week", "Side", "Anchor", "Fixing", "Move", "Floor", "Cap", "Unhedged $/GPU-h", "Unhedged $/week"],
          s.capped_weeks.map((c) => [c.week, c.side, c.anchor.toFixed(3), c.fixing.toFixed(3), signedPct(c.move), c.floor.toFixed(3), c.cap.toFixed(3), c.unhedged_excess_usd_per_gpu_hour.toFixed(3), money(c.unhedged_excess_usd_per_week)])
        )
      : "None.",
  );
  out.push("");
  out.push("## 3. Sensitivity to the clearing price");
  out.push("");
  out.push("The forward `floor + p` set at the anchor times (1 + shift). A positive shift means buyers paid up to hedge; a negative shift means sellers did.");
  out.push("");
  out.push(
    table(
      ["Forward vs anchor", "Buyer hedged total", "Buyer cost of hedging", "Buyer surprise sd", "Seller hedged total", "Seller gain from hedging", "Buyer lock / week", "Seller lock / week"],
      s.sensitivity.map((h) => [
        signedPct(h.forward_shift),
        money(h.buyer.hedged_weekly_cost.total),
        money(h.buyer.hedge_cost_total),
        money(h.buyer.sd_of_surprise.hedged),
        money(h.seller.hedged_weekly_revenue.total),
        money(h.seller.hedge_gain_total),
        money(h.buyer.locked_per_week.mean),
        money(h.seller.locked_per_week.mean),
      ]),
    ),
  );
  out.push("");
  out.push(`Unhedged total for comparison: ${money(s.hedge_neutral.buyer.unhedged_weekly_cost.total)}. A positive "cost of hedging" is what the buyer paid over spot across the whole sample; the seller's gain is the mirror image.`);
  out.push("");
  out.push("## 4. Basis risk: hedging one provider's bill with the index");
  out.push("");
  out.push(`Spot is the provider's own weekly mean price; the hedge settles on the index at band_bps = ${rec.band_bps}, neutral price. "Variance removed" is on the weekly cost surprise. Providers need ${P.minProviderWeeks} usable weeks.`);
  out.push("");
  const enough = s.basis_risk.filter((b) => b.enough_history);
  out.push(
    table(
      ["Provider", "In composite", "Weeks", "Mean $/GPU-h", "Surprise sd unhedged", "Surprise sd hedged", "Variance removed", "Corr. with index moves", "Verdict"],
      enough.map((b) => [
        b.provider,
        b.in_composite ? "yes" : "no",
        b.weeks,
        (b.mean_price ?? 0).toFixed(3),
        money(b.sd_weekly_cost_surprise?.unhedged ?? 0),
        money(b.sd_weekly_cost_surprise?.hedged ?? 0),
        pct(b.surprise_variance_removed ?? null),
        b.correlation_of_moves_with_index == null ? "n/a" : b.correlation_of_moves_with_index.toFixed(2),
        b.verdict ?? "",
      ]),
    ),
  );
  const thin = s.basis_risk.filter((b) => !b.enough_history);
  if (thin.length) out.push("", `Too little history: ${thin.map((b) => `${b.provider} (${b.weeks} weeks)`).join(", ")}.`);
  out.push("");
  out.push("## 5. Falling and rising markets");
  out.push("");
  const R = s.regimes;
  if (R.falling && R.rising) {
    out.push(`Split at ${R.trough_week} (${R.rule}).`);
    out.push("");
    const rows = [R.falling, R.rising].map((r, i) => {
      const cov = r.coverage.find((c) => c.band_bps === rec.band_bps)!;
      return [
        i === 0 ? "Falling" : "Rising",
        `${r.first_week} to ${r.last_week}`,
        r.weeks,
        r.mean_fixing.toFixed(3),
        signedPct(r.move.mean),
        pct(r.move.sd),
        pct(cov.share_inside),
        money(r.hedge_neutral.buyer.sd_of_surprise.unhedged),
        money(r.hedge_neutral.buyer.sd_of_surprise.hedged),
        money(r.hedge_neutral.buyer.hedge_cost_total),
      ];
    });
    out.push(
      table(
        ["Regime", "Weeks", "n", "Mean fixing", "Mean move", "Move sd", `Inside at ${rec.band_bps}`, "Buyer surprise sd unhedged", "hedged", "Buyer cost of hedging (neutral)"],
        rows,
      ),
    );
    out.push("");
    out.push("Coverage by band in each regime:");
    out.push("");
    out.push(
      table(
        ["band_bps", "Falling: inside", "Rising: inside"],
        R.falling.coverage.map((c, i) => [c.band_bps, `${c.inside}/${c.weeks} (${pct(c.share_inside)})`, `${R.rising!.coverage[i]!.inside}/${R.rising!.coverage[i]!.weeks} (${pct(R.rising!.coverage[i]!.share_inside)})`]),
      ),
    );
  } else {
    out.push("The data show no interior trough; no split was made.");
  }
  out.push("");
  out.push("## What this does not show");
  out.push("");
  out.push(
    [
      "- **No real order flow.** Nobody traded these weeks. The clearing price is assumed (at the anchor, or shifted ±2% and ±5%); a real auction could clear further away, or not at all in a quiet week.",
      "- **Asks and rate cards, not trades.** The index is the median of providers' posted on-demand prices. Posted prices are sticky: a provider can keep a list price for months while discounts, availability and negotiated deals move underneath. Low measured volatility partly reflects that stickiness, not a calm market." + ornnText,
      `- **Sample length.** The sources reach back to ${s.data.first_day}, but before ${s.data.first_index_day} fewer than 4 market providers are in the data, so the index (and the backtest) covers ${s.data.first_index_day} to ${s.data.last_index_day}: ${s.weeks.kept} usable weeks, one gentle decline and one sharp rise. The 2024 to early-2025 price fall is not in the sample. Tail estimates (the 95% band) rest on a handful of weeks.`,
      `- **Provider survivorship and composition.** The composite uses whoever is in the sources on a day: the set changed on ${"composition_changes" in s.robustness_fixed_panel ? s.robustness_fixed_panel.composition_changes : "many"} index days. Providers enter (Akash from 2025-07, Cudo and Vast.ai from 2026-01, others in 2026-10) and change their SKU mix; the median can step when the set changes, without any provider changing price. Providers that left the market before or during the window are not represented.`,
      "- **Gaps.** Days without at least 4 providers have no index value and are never filled. Weeks with fewer than 4 daily values or a stale anchor are dropped, and dropped weeks may not be random (scrapes fail more often when things change).",
      "- **Daily prints, not the on-chain cadence.** The contract may print more often than once a day; one daily snapshot is a coarse stand-in, taken at whatever hour the source ran.",
      "- **Usage and fees.** Flat usage of 8 GPUs every hour; no fees, no cost of locked capital, no bonus pool, no forfeits.",
      "- **Hyperscalers are excluded from the index** and appear only in the basis-risk table.",
    ].join("\n"),
  );
  out.push("");
  return out.join("\n");
}
