/** Characters the face can draw. Anything else is drawn as a space (and stays in the text). */
export const GLYPHS = Object.keys(G);

export interface DotLayout {
  /** Width in grid units, including the final gap column removed. */
  width: number;
  /** Lit dots as [column, row]. */
  dots: [number, number][];
}

/** Lays out a string on the grid. Pure: the tests check widths and a few glyphs. */
export function layoutDots(text: string): DotLayout {
  const dots: [number, number][] = [];
  let x = 0;
  for (const ch of text) {
    const g = G[ch] ?? G[" "]!;
    const w = g[0]!.length;
    g.forEach((row, y) => {
      for (let c = 0; c < row.length; c++) if (row[c] === "#") dots.push([x + c, y]);
    });
    x += w + 1;
  }
  return { width: Math.max(0, x - 1), dots };
}

/** One SVG path for a whole string: a square dot per lit cell, `size` of the pitch. */
export function dotPath(text: string, size = 0.78): { width: number; d: string } {
  const { width, dots } = layoutDots(text);
  const o = (1 - size) / 2;
  const s = +size.toFixed(3);
  const d = dots.map(([c, r]) => `M${+(c + o).toFixed(3)} ${+(r + o).toFixed(3)}h${s}v${s}h-${s}z`).join("");
  return { width, d };
}
